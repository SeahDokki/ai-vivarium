const STORAGE_KEY = "vivarium.lang";

function initialLang() {
  try {
    const saved = localStorage.getItem(STORAGE_KEY);
    if (saved && DICT[saved]) return saved;
  } catch {
    /* storage blocked: follow the browser */
  }
  for (const l of navigator.languages ?? [navigator.language]) {
    const short = String(l).slice(0, 2).toLowerCase();
    if (DICT[short]) return short;
  }
  return "en";
}

export let lang = initialLang();

/** The text for `key` in the current language ({name} placeholders filled from `vars`). Falls back to English, then the key. */
export function t(key, vars) {
  const text = DICT[lang][key] ?? DICT.en[key] ?? key;
  return vars ? text.replace(/\{(\w+)\}/g, (m, k) => (k in vars ? String(vars[k]) : m)) : text;
}

export const locale = () => LOCALES[lang];

/** Translate the static text of the page. */
export function applyI18n(root = document) {
  document.documentElement.lang = lang;
  for (const node of root.querySelectorAll("[data-i18n]")) node.textContent = t(node.dataset.i18n);
  for (const node of root.querySelectorAll("[data-i18n-attr]")) {
    for (const pair of node.dataset.i18nAttr.split(";")) {
      const [attr, key] = pair.split(":");
      if (attr && key) node.setAttribute(attr.trim(), t(key.trim()));
    }
  }
}

/** Fill a <select> with the languages; changing it re-translates the page and calls `onChange`. */
export function mountLanguagePicker(select, onChange) {
  select.replaceChildren();
  for (const [code, label] of LANGS) {
    const option = document.createElement("option");
    option.value = code;
    option.textContent = label;
    option.selected = code === lang;
    select.append(option);
  }
  select.setAttribute("aria-label", t("lang.label"));
  select.addEventListener("change", () => {
    if (!DICT[select.value]) return;
    lang = select.value;
    try {
      localStorage.setItem(STORAGE_KEY, lang);
    } catch {
      /* not remembered: fine */
    }
    applyI18n();
    select.setAttribute("aria-label", t("lang.label"));
    onChange?.();
  });
}
